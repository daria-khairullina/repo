# Введення значення радіусу з клавіатури
R = float(input("Радіус кола: "))
a = 6
# Обчислення радіуса кола описаного навкола трикутника зі стороною 6
r_trukytnuka = (a*(3**0.5))/3

# Умова та її перевірка
if R >= r_trukytnuka:
    print("Трикутник поміститься")
else:
    print("Трикутник не поміститься")
