# Введення значення змінних v, v1, t1, t2 з клавіатури
v = float(input("Швидкість човна в стоячій воді (км/год): "))
v2 = float(input("Швидкість течії (км/год): "))
t1 = float(input("Час руху по озеру (год): "))
t2 = float(input("Час руху проти течії річки (год): "))

# Обчислення загальної відстані
result = v*t1 + (abs(v - v2))*t2

# Виведення результату
print(result)
